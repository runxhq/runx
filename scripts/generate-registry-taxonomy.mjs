#!/usr/bin/env node
// Project the registry taxonomy (registry/taxonomy.json) into the Rust
// contract, which the parser checks declared categories against, and into
// @runxhq/contracts, which the hosted registry serves with each category's
// mark. registry/taxonomy.json is the only place a category is defined.
import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const workspaceRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const taxonomyRoot = path.join(workspaceRoot, "registry");
const rustPath = path.join(workspaceRoot, "crates", "runx-contracts", "src", "registry_taxonomy", "generated.rs");
const contractsPath = path.join(workspaceRoot, "packages", "contracts", "src", "generated", "registry-taxonomy.ts");
const check = process.argv.includes("--check");
const ID = /^[a-z][a-z0-9-]{0,31}$/u;
const SUBJECTS = new Set(["skill", "connector"]);
const SURFACES = new Set(["domain", "builder"]);

function fail(message) {
  throw new Error(`registry/taxonomy.json: ${message}`);
}

function readMark(relative, location) {
  if (typeof relative !== "string" || !relative.startsWith("marks/") || relative.includes("..")) {
    fail(`${location}.mark must name a file under registry/marks`);
  }
  const file = path.join(taxonomyRoot, relative);
  if (!existsSync(file)) fail(`${location}.mark ${relative} does not exist`);
  const svg = readFileSync(file, "utf8");
  return { svg, digest: createHash("sha256").update(svg).digest("hex") };
}

function load() {
  const document = JSON.parse(readFileSync(path.join(taxonomyRoot, "taxonomy.json"), "utf8"));
  if (document.schema !== "runx.registry_taxonomy.v1") fail("schema must be runx.registry_taxonomy.v1");
  const seen = new Set();
  const categories = document.categories.map((category, index) => {
    const location = `categories[${index}]`;
    if (!ID.test(category.id ?? "")) fail(`${location}.id must match ${ID}`);
    if (seen.has(category.id) || category.id === document.uncategorized.id) fail(`${location}.id ${category.id} is declared twice`);
    seen.add(category.id);
    for (const field of ["label", "description"]) {
      if (typeof category[field] !== "string" || category[field].trim() === "") fail(`${location}.${field} must be text`);
    }
    const appliesTo = category.applies_to;
    if (!Array.isArray(appliesTo) || appliesTo.length === 0 || appliesTo.some((subject) => !SUBJECTS.has(subject))) {
      fail(`${location}.applies_to must list skill and/or connector`);
    }
    if (!SURFACES.has(category.surface)) fail(`${location}.surface must be domain or builder`);
    return { ...category, mark: readMark(category.mark, location) };
  });
  const uncategorized = document.uncategorized;
  if (!ID.test(uncategorized.id ?? "") || typeof uncategorized.label !== "string") fail("uncategorized needs an id and label");
  return { categories, uncategorized: { ...uncategorized, mark: readMark(uncategorized.mark, "uncategorized") } };
}

const rustString = (value) => JSON.stringify(value);

function renderRust({ categories, uncategorized }) {
  const rows = categories.map((category) => [
    "    Category {",
    `        id: ${rustString(category.id)},`,
    `        label: ${rustString(category.label)},`,
    `        skill: ${category.applies_to.includes("skill")},`,
    `        connector: ${category.applies_to.includes("connector")},`,
    `        builder: ${category.surface === "builder"},`,
    "    },",
  ].join("\n"));
  return [
    "// Generated by scripts/generate-registry-taxonomy.mjs from registry/taxonomy.json; do not edit.",
    "",
    "use super::Category;",
    "",
    `pub(super) const UNCATEGORIZED: &str = ${rustString(uncategorized.id)};`,
    "",
    "pub(super) const CATEGORIES: &[Category] = &[",
    ...rows,
    "];",
    "",
  ].join("\n");
}

function renderContracts({ categories, uncategorized }) {
  const project = (category) => ({
    id: category.id,
    label: category.label,
    ...(category.description ? { description: category.description } : {}),
    ...(category.applies_to ? { applies_to: category.applies_to } : {}),
    ...(category.surface ? { surface: category.surface } : {}),
    mark: { digest: category.mark.digest, svg: category.mark.svg },
  });
  return [
    "// Generated by scripts/generate-registry-taxonomy.mjs from registry/taxonomy.json; do not edit.",
    "",
    'import type { RegistryTaxonomy } from "../registry-taxonomy.js";',
    "",
    `export const registryTaxonomy: RegistryTaxonomy = ${JSON.stringify({
      uncategorized: project(uncategorized),
      categories: categories.map(project),
    }, null, 2)};`,
    "",
  ].join("\n");
}

const taxonomy = load();
const outputs = [
  [rustPath, renderRust(taxonomy)],
  [contractsPath, renderContracts(taxonomy)],
];
let stale = false;
for (const [file, contents] of outputs) {
  const current = existsSync(file) ? readFileSync(file, "utf8") : undefined;
  if (current === contents) continue;
  if (check) {
    stale = true;
    process.stderr.write(`${path.relative(workspaceRoot, file)} is out of date; run node scripts/generate-registry-taxonomy.mjs\n`);
  } else {
    writeFileSync(file, contents);
  }
}
if (stale) process.exit(1);
