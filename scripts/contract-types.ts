// Render the TypeScript contract types from the generated JSON Schemas, so a
// TS consumer reads the same shapes, under the same names, that Rust writes,
// and no contract type is kept by hand.

type Schema = { readonly [key: string]: unknown };

export interface ContractTypeSource {
  /** `receipt.schema.json` */
  readonly fileName: string;
  /** The Rust type the schema is generated from, `Receipt`. */
  readonly typeName: string;
  readonly schema: Schema;
}

const IDENTIFIER = /^[A-Za-z_$][A-Za-z0-9_$]*$/u;

/**
 * One `export type` per named Rust contract type, `Receipt` as
 * `ReceiptContract`. `types` holds each one's own schema by name, as Rust
 * records it; a schema anywhere that carries a type's name as its `title` is
 * that type, and must be its shape.
 */
export function renderContractTypes(
  sources: readonly ContractTypeSource[],
  types: Readonly<Record<string, Schema>>,
): string {
  for (const source of sources) {
    if (!(source.typeName in types)) {
      throw new Error(`${source.fileName} comes from ${source.typeName}, which records no schema`);
    }
    checkTitles(source.schema, types, source.fileName);
  }

  const blocks = Object.keys(types)
    .sort((left, right) => left.localeCompare(right))
    .map((title) => {
      const schema = types[title] as Schema;
      const body = new Renderer(title, types).render(schema, "");
      return `${jsDoc(describedAs(schema), "")}export type ${contractName(title)} = ${body};`;
    });

  return [
    "// Generated by scripts/generate-contract-schemas.ts. Do not edit by hand.",
    "// Source of truth: the Rust contract types behind schemas/*.schema.json.",
    "",
    blocks.join("\n\n"),
    "",
  ].join("\n");
}

/** Every titled schema under `value` is the named type of that title. */
function checkTitles(value: unknown, types: Readonly<Record<string, Schema>>, at: string): void {
  if (Array.isArray(value)) {
    value.forEach((item, index) => checkTitles(item, types, `${at}[${index}]`));
    return;
  }
  const schema = asSchema(value);
  if (!schema) return;
  const title = schema.title;
  if (typeof title === "string") {
    const own = types[title];
    if (!own) throw new Error(`${at} is titled ${title}, which records no schema`);
    if (shapeOf(own) !== shapeOf(schema)) {
      throw new Error(`${at} is titled ${title} but is not its shape; a narrowed schema drops the title`);
    }
  }
  for (const [key, child] of Object.entries(schema)) checkTitles(child, types, `${at}/${key}`);
}

class Renderer {
  constructor(
    private readonly declaring: string,
    private readonly types: Readonly<Record<string, Schema>>,
  ) {}

  render(schema: Schema, indent: string): string {
    const title = schema.title;
    if (typeof title === "string" && title !== this.declaring) return contractName(title);
    const ref = schema.$ref;
    if (typeof ref === "string") return this.definition(ref);
    if ("const" in schema) return literal(schema.const);
    if (Array.isArray(schema.enum)) return union(schema.enum.map(literal));
    for (const keyword of ["anyOf", "oneOf"] as const) {
      const variants = schema[keyword];
      if (Array.isArray(variants)) {
        return union(variants.map((variant, index) => this.render(schemaOf(variant, `${keyword}[${index}]`), indent)));
      }
    }
    const allOf = schema.allOf;
    if (Array.isArray(allOf)) {
      return allOf.map((part, index) => wrap(this.render(schemaOf(part, `allOf[${index}]`), indent))).join(" & ");
    }
    const type = schema.type;
    if (Array.isArray(type)) return union(type.map((member) => this.typed(schema, String(member), indent)));
    if (typeof type === "string") return this.typed(schema, type, indent);
    if (schema.properties || schema.additionalProperties !== undefined || schema.patternProperties) {
      return this.object(schema, indent);
    }
    return "unknown";
  }

  private typed(schema: Schema, type: string, indent: string): string {
    switch (type) {
      case "string":
        return "string";
      case "integer":
      case "number":
        return "number";
      case "boolean":
        return "boolean";
      case "null":
        return "null";
      case "array": {
        const items = asSchema(schema.items);
        return `readonly ${wrap(items ? this.render(items, indent) : "unknown")}[]`;
      }
      case "object":
        return this.object(schema, indent);
      default:
        throw new Error(`unsupported JSON Schema type ${type}`);
    }
  }

  private object(schema: Schema, indent: string): string {
    const inner = `${indent}  `;
    const required = new Set(Array.isArray(schema.required) ? schema.required.map(String) : []);
    const members: string[] = [];
    for (const [key, value] of Object.entries(asSchema(schema.properties) ?? {})) {
      const property = schemaOf(value, key);
      const optional = required.has(key) ? "" : "?";
      members.push(
        `${jsDoc(this.propertyDoc(property), inner)}${inner}readonly ${propertyKey(key)}${optional}: ${this.render(property, inner)};`,
      );
    }
    const open = this.openValues(schema, inner);
    if (open) members.push(`${inner}readonly [key: string]: ${open};`);
    if (members.length === 0) return "{}";
    return `{\n${members.join("\n")}\n${indent}}`;
  }

  /** A property's own description, unless it only repeats its type's. */
  private propertyDoc(property: Schema): string | undefined {
    const doc = describedAs(property);
    const title = property.title;
    const own = typeof title === "string" ? this.types[title] : undefined;
    return own && describedAs(own) === doc ? undefined : doc;
  }

  /** The type of the values an object admits beyond its named properties. */
  private openValues(schema: Schema, indent: string): string | undefined {
    const values: string[] = [];
    const additional = schema.additionalProperties;
    if (additional === undefined || additional === true) {
      values.push("unknown");
    } else if (additional !== false) {
      values.push(this.render(schemaOf(additional, "additionalProperties"), indent));
    }
    for (const [pattern, value] of Object.entries(asSchema(schema.patternProperties) ?? {})) {
      values.push(this.render(schemaOf(value, pattern), indent));
    }
    if (values.length === 0) return undefined;
    // An index signature must admit every named property's type too.
    return schema.properties ? "unknown" : union(values);
  }

  private definition(ref: string): string {
    const definition = /^#\/\$defs\/(.+)$/u.exec(ref)?.[1];
    if (!definition || !(definition in this.types)) {
      throw new Error(`${this.declaring} has an unresolved $ref ${ref}`);
    }
    return contractName(definition);
  }
}

function contractName(typeName: string): string {
  return `${typeName}Contract`;
}

/** A schema's shape: what it admits, without what documents or marks it. */
function shapeOf(schema: Schema): string {
  const strip = (value: unknown): unknown => {
    if (Array.isArray(value)) return value.map(strip);
    const object = asSchema(value);
    if (!object) return value;
    return Object.fromEntries(
      Object.keys(object)
        .filter((key) => !["description", "$id", "$schema", "x-runx-packet"].includes(key))
        .sort()
        .map((key) => [key, strip(object[key])]),
    );
  };
  return JSON.stringify(strip(schema));
}

function describedAs(schema: Schema): string | undefined {
  const description = schema.description;
  return typeof description === "string" && description.trim() !== "" ? description.trim() : undefined;
}

/** Parenthesize a union or intersection so a suffix binds to all of it. */
function wrap(type: string): string {
  let depth = 0;
  for (const character of type) {
    if (character === "{" || character === "(" || character === "[") depth += 1;
    else if (character === "}" || character === ")" || character === "]") depth -= 1;
    else if (depth === 0 && (character === "|" || character === "&")) return `(${type})`;
  }
  return type;
}

function union(members: readonly string[]): string {
  const unique = [...new Set(members)];
  if (unique.includes("unknown")) return "unknown";
  return unique.length === 0 ? "never" : unique.join(" | ");
}

function literal(value: unknown): string {
  return JSON.stringify(value);
}

function propertyKey(key: string): string {
  return IDENTIFIER.test(key) ? key : JSON.stringify(key);
}

function jsDoc(description: string | undefined, indent: string): string {
  if (!description) return "";
  const lines = description.replace(/\*\//gu, "*\\/").split("\n");
  if (lines.length === 1) return `${indent}/** ${lines[0]} */\n`;
  return `${indent}/**\n${lines.map((line) => `${indent} *${line ? ` ${line}` : ""}`).join("\n")}\n${indent} */\n`;
}

function asSchema(value: unknown): Schema | undefined {
  return value && typeof value === "object" && !Array.isArray(value) ? (value as Schema) : undefined;
}

function schemaOf(value: unknown, at: string): Schema {
  if (value === true) return {};
  const schema = asSchema(value);
  if (!schema) throw new Error(`schema at ${at} is not an object`);
  return schema;
}
