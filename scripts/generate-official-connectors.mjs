#!/usr/bin/env node
// Embed the official connector manifests in the runtime, so an installed runx
// resolves official connectors without the source tree, and in
// @runxhq/contracts, so runx Connect reads the same declarations. The runtime
// parses and validates them once per process. Digests are computed in Rust
// only: the contracts module is what runx-official-connectors prints.
import { spawnSync } from "node:child_process";
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const workspaceRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const connectorsRoot = path.join(workspaceRoot, "connectors");
const outputPath = path.join(
  workspaceRoot,
  "crates",
  "runx-runtime",
  "src",
  "kernel",
  "connectors",
  "official.rs",
);
const contractsPath = path.join(
  workspaceRoot,
  "packages",
  "contracts",
  "src",
  "generated",
  "official-connectors.ts",
);
const check = process.argv.includes("--check");
const delimiter = "###";

function manifests() {
  return readdirSync(connectorsRoot, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort()
    .map((id) => {
      const file = path.join(connectorsRoot, id, "connector.yaml");
      if (!existsSync(file)) {
        throw new Error(`connectors/${id} has no connector.yaml`);
      }
      return { id, source: readFileSync(file, "utf8") };
    });
}

function literal({ id, source }) {
  if (source.includes(`"${delimiter}`)) {
    throw new Error(`${id} contains the raw string delimiter`);
  }
  return `    (\n        "${id}",\n        r${delimiter}"${source}"${delimiter},\n    ),`;
}

function render() {
  return [
    "// Generated by scripts/generate-official-connectors.mjs; do not edit.",
    "// Module rationale: the embedded official manifests are one generated table",
    "// so a connector change is a single mechanical, reviewable diff.",
    "",
    "/// Official connector manifests, by id.",
    "pub(super) const CONNECTORS: &[(&str, &str)] = &[",
    ...manifests().map(literal),
    "];",
    "",
  ].join("\n");
}

function renderContracts() {
  const cargo = process.platform === "win32" ? "cargo.exe" : "cargo";
  const prebuilt = process.env.RUNX_OFFICIAL_CONNECTORS_BIN;
  const result = spawnSync(
    prebuilt || cargo,
    prebuilt ? [connectorsRoot] : [
      "run",
      "--quiet",
      "--manifest-path",
      path.join(workspaceRoot, "crates", "Cargo.toml"),
      "-p",
      "runx-parser",
      "--bin",
      "runx-official-connectors",
      "--",
      connectorsRoot,
    ],
    { cwd: workspaceRoot, encoding: "utf8", maxBuffer: 64 * 1024 * 1024, stdio: ["ignore", "pipe", "inherit"] },
  );
  if (result.error) throw result.error;
  if (result.status !== 0) process.exit(result.status ?? 1);
  return [
    "// Generated by scripts/generate-official-connectors.mjs; do not edit.",
    "// Validated and digested in Rust by runx-official-connectors.",
    "",
    'import type { OfficialConnector } from "../connector.js";',
    "",
    `export const officialConnectors: readonly OfficialConnector[] = ${JSON.stringify(JSON.parse(result.stdout), null, 2)};`,
    "",
  ].join("\n");
}

const outputs = [
  [outputPath, render()],
  [contractsPath, renderContracts()],
];
let stale = false;
for (const [file, output] of outputs) {
  if (check) {
    const existing = existsSync(file) ? readFileSync(file, "utf8") : "";
    if (existing !== output) {
      console.error(`${path.relative(workspaceRoot, file)} is stale; run pnpm official-connectors:generate`);
      stale = true;
    }
  } else {
    writeFileSync(file, output);
  }
}
if (stale) process.exit(1);
