#!/usr/bin/env node
// Embed the runx-maintained connector manifests, and the tool packages their process
// operations run, in the runtime, so an installed runx resolves runx-maintained
// connectors without the source tree, and the manifests in @runxhq/contracts,
// so runx Connect reads the same declarations. The runtime parses and
// validates them once per process. Digests are computed in Rust only: the
// contracts module is what runx-maintained-connectors prints. The lock,
// registry/runx-maintained-connectors.lock.json, is the version each connector
// publishes as, read by the native packager;
// scripts/publish-runx-maintained-connectors.mjs publishes from it.
import { spawnSync } from "node:child_process";
import { existsSync, lstatSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const workspaceRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const connectorsRoot = path.join(workspaceRoot, "connectors");
const outputPath = path.join(
  workspaceRoot,
  "crates",
  "runx-runtime",
  "src",
  "kernel",
  "connectors",
  "runx_maintained.rs",
);
const contractsPath = path.join(
  workspaceRoot,
  "packages",
  "contracts",
  "src",
  "generated",
  "runx-maintained-connectors.ts",
);
const lockPath = path.join(workspaceRoot, "registry", "runx-maintained-connectors.lock.json");
const check = process.argv.includes("--check");
const delimiter = "###";

function manifests() {
  return readdirSync(connectorsRoot, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort()
    .map((id) => {
      const file = path.join(connectorsRoot, id, "connector.yaml");
      if (!existsSync(file)) {
        throw new Error(`connectors/${id} has no connector.yaml`);
      }
      return { id, source: readFileSync(file, "utf8") };
    });
}

// The entries a tool package never ships, as the runtime reads one.
const IGNORED = new Set([".git", ".runx", "node_modules", "target"]);

// Every file below each connector's tools/, by connector and the path below it.
function tools() {
  const files = [];
  for (const { id } of manifests()) {
    const root = path.join(connectorsRoot, id, "tools");
    if (!existsSync(root)) continue;
    const walk = (dir) => {
      for (const name of readdirSync(dir).sort()) {
        if (IGNORED.has(name)) continue;
        const file = path.join(dir, name);
        const stat = lstatSync(file);
        if (stat.isSymbolicLink()) throw new Error(`${path.relative(workspaceRoot, file)} is a link`);
        if (stat.isDirectory()) walk(file);
        else {
          const bytes = readFileSync(file);
          const source = bytes.toString("utf8");
          if (!Buffer.from(source, "utf8").equals(bytes)) throw new Error(`${path.relative(workspaceRoot, file)} is not UTF-8`);
          files.push({ id, path: path.relative(root, file).split(path.sep).join("/"), source });
        }
      }
    };
    walk(root);
  }
  return files;
}

function toolLiteral({ id, path: file, source }) {
  if (source.includes(`"${delimiter}`)) {
    throw new Error(`${id}/tools/${file} contains the raw string delimiter`);
  }
  return `    (\n        "${id}",\n        "${file}",\n        r${delimiter}"${source}"${delimiter},\n    ),`;
}

function assets() {
  return manifests().flatMap(({ id }) => ["README.md", "mark.svg"].flatMap((file) => {
    const source = path.join(connectorsRoot, id, file);
    return existsSync(source) ? [{ id, path: file, source: readFileSync(source, "utf8") }] : [];
  }));
}

function literal({ id, source }) {
  if (source.includes(`"${delimiter}`)) {
    throw new Error(`${id} contains the raw string delimiter`);
  }
  return `    (\n        "${id}",\n        r${delimiter}"${source}"${delimiter},\n    ),`;
}

function render() {
  return [
    "// Generated by scripts/generate-runx-maintained-connectors.mjs; do not edit.",
    "// Module rationale: the embedded runx-maintained manifests are one generated table",
    "// so a connector change is a single mechanical, reviewable diff.",
    "",
    "/// Runx-maintained connector manifests, by id.",
    "pub(super) const CONNECTORS: &[(&str, &str)] = &[",
    ...manifests().map(literal),
    "];",
    "",
    "/// The files of the tool packages runx-maintained connectors ship: the connector,",
    "/// the path below its tools/, and the contents.",
    "pub(super) const TOOLS: &[(&str, &str, &str)] = &[",
    ...tools().map(toolLiteral),
    "];",
    "",
    "/// Public package assets, retained so offline snapshots preserve published bytes.",
    "pub(super) const ASSETS: &[(&str, &str, &str)] = &[",
    ...assets().map(toolLiteral),
    "];",
    "",
  ].join("\n");
}

// What runx-maintained-connectors prints for these arguments and the connectors directory.
function runxMaintainedConnectors(args = []) {
  const cargo = process.platform === "win32" ? "cargo.exe" : "cargo";
  const prebuilt = process.env.RUNX_OFFICIAL_CONNECTORS_BIN;
  const result = spawnSync(
    prebuilt || cargo,
    prebuilt ? [...args, connectorsRoot] : [
      "run",
      "--quiet",
      "--manifest-path",
      path.join(workspaceRoot, "crates", "Cargo.toml"),
      "-p",
      "runx-runtime",
      "--bin",
      "runx-maintained-connectors",
      "--",
      ...args,
      connectorsRoot,
    ],
    { cwd: workspaceRoot, encoding: "utf8", maxBuffer: 64 * 1024 * 1024, stdio: ["ignore", "pipe", "inherit"] },
  );
  if (result.error) throw result.error;
  if (result.status !== 0) process.exit(result.status ?? 1);
  return JSON.parse(result.stdout);
}

function renderContracts() {
  return [
    "// Generated by scripts/generate-runx-maintained-connectors.mjs; do not edit.",
    "// Validated and digested in Rust by runx-maintained-connectors.",
    "",
    'import type { RunxMaintainedConnector } from "../connector.js";',
    "",
    `export const runxMaintainedConnectors: readonly RunxMaintainedConnector[] = ${JSON.stringify(runxMaintainedConnectors(), null, 2)};`,
    "",
  ].join("\n");
}

function renderLock() {
  return `${JSON.stringify(runxMaintainedConnectors(["--lock"]), null, 2)}\n`;
}

// The runtime table first: the contracts module is printed by a runtime that
// compiles it, so it must be current before that runtime is built.
function settle(file, output) {
  if (!check) {
    writeFileSync(file, output);
    return;
  }
  const existing = existsSync(file) ? readFileSync(file, "utf8") : "";
  if (existing !== output) {
    console.error(`${path.relative(workspaceRoot, file)} is stale; run pnpm runx-maintained-connectors:generate`);
    process.exit(1);
  }
}
settle(outputPath, render());
settle(contractsPath, renderContracts());
settle(lockPath, renderLock());
