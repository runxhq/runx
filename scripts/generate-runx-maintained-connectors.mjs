#!/usr/bin/env node
// Embed the runtime capability connectors (a manifest declaring
// `runtime_capability: true`) in the runtime: they are part of runx, implemented
// by the runtime and shipping no tool package, so an installed runx resolves
// them without the source tree or a registry. Every other runx-maintained
// connector is a published package, fetched like any non-core skill. All the
// runx-maintained manifests go into @runxhq/contracts, so runx Connect reads
// the same declarations. Digests are computed in Rust only: the contracts
// module is what runx-maintained-connectors prints. The lock,
// registry/runx-maintained-connectors.lock.json, is the version each connector
// publishes as, read by the native packager;
// scripts/publish-runx-maintained-connectors.mjs publishes from it.
import { spawnSync } from "node:child_process";
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const workspaceRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const connectorsRoot = path.join(workspaceRoot, "connectors");
const outputPath = path.join(
  workspaceRoot,
  "crates",
  "runx-runtime",
  "src",
  "kernel",
  "connectors",
  "runtime_capabilities.rs",
);
const contractsPath = path.join(
  workspaceRoot,
  "packages",
  "contracts",
  "src",
  "generated",
  "runx-maintained-connectors.ts",
);
const lockPath = path.join(workspaceRoot, "registry", "runx-maintained-connectors.lock.json");
const check = process.argv.includes("--check");
const delimiter = "###";

function manifests() {
  return readdirSync(connectorsRoot, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort()
    .map((id) => {
      const file = path.join(connectorsRoot, id, "connector.yaml");
      if (!existsSync(file)) {
        throw new Error(`connectors/${id} has no connector.yaml`);
      }
      return { id, source: readFileSync(file, "utf8") };
    });
}

function assetLiteral({ id, path: file, source }) {
  if (source.includes(`"${delimiter}`)) {
    throw new Error(`${id}/${file} contains the raw string delimiter`);
  }
  return `    (\n        "${id}",\n        "${file}",\n        r${delimiter}"${source}"${delimiter},\n    ),`;
}

function assets(embedded) {
  return embedded.flatMap(({ id }) => ["README.md", "mark.svg"].flatMap((file) => {
    const source = path.join(connectorsRoot, id, file);
    return existsSync(source) ? [{ id, path: file, source: readFileSync(source, "utf8") }] : [];
  }));
}

function literal({ id, source }) {
  if (source.includes(`"${delimiter}`)) {
    throw new Error(`${id} contains the raw string delimiter`);
  }
  return `    (\n        "${id}",\n        r${delimiter}"${source}"${delimiter},\n    ),`;
}

// The connectors the runtime embeds: those whose validated manifest declares
// itself a runtime capability.
function embeddedManifests(contract) {
  const capabilities = new Set(
    contract.filter((entry) => entry.manifest.runtime_capability === true).map((entry) => entry.manifest.id),
  );
  const embedded = manifests().filter(({ id }) => capabilities.has(id));
  for (const { id } of embedded) {
    if (existsSync(path.join(connectorsRoot, id, "tools"))) {
      throw new Error(`connectors/${id} is a runtime capability, implemented by the runtime; it ships no tools/`);
    }
  }
  return embedded;
}

function render(contract) {
  const embedded = embeddedManifests(contract);
  return [
    "// Generated by scripts/generate-runx-maintained-connectors.mjs; do not edit.",
    "// Module rationale: the embedded runtime capability manifests are one generated",
    "// table so a change is a single mechanical, reviewable diff.",
    "",
    "/// Runtime capability connector manifests, by id.",
    "pub(super) const CONNECTORS: &[(&str, &str)] = &[",
    ...embedded.map(literal),
    "];",
    "",
    "/// Public package assets, retained so offline snapshots preserve published bytes.",
    "pub(super) const ASSETS: &[(&str, &str, &str)] = &[",
    ...assets(embedded).map(assetLiteral),
    "];",
    "",
  ].join("\n");
}

// What runx-maintained-connectors prints for these arguments and the connectors directory.
function runxMaintainedConnectors(args = []) {
  const cargo = process.platform === "win32" ? "cargo.exe" : "cargo";
  const prebuilt = process.env.RUNX_OFFICIAL_CONNECTORS_BIN;
  const result = spawnSync(
    prebuilt || cargo,
    prebuilt ? [...args, connectorsRoot] : [
      "run",
      "--quiet",
      "--manifest-path",
      path.join(workspaceRoot, "crates", "Cargo.toml"),
      "-p",
      "runx-runtime",
      "--example",
      "runx-maintained-connectors",
      "--",
      ...args,
      connectorsRoot,
    ],
    { cwd: workspaceRoot, encoding: "utf8", maxBuffer: 64 * 1024 * 1024, stdio: ["ignore", "pipe", "inherit"] },
  );
  if (result.error) throw result.error;
  if (result.status !== 0) process.exit(result.status ?? 1);
  return JSON.parse(result.stdout);
}

function renderContracts(contract) {
  return [
    "// Generated by scripts/generate-runx-maintained-connectors.mjs; do not edit.",
    "// Validated and digested in Rust by runx-maintained-connectors.",
    "",
    'import type { RunxMaintainedConnector } from "../connector.js";',
    "",
    `export const runxMaintainedConnectors: readonly RunxMaintainedConnector[] = ${JSON.stringify(contract, null, 2)};`,
    "",
  ].join("\n");
}

function renderLock() {
  return `${JSON.stringify(runxMaintainedConnectors(["--lock"]), null, 2)}\n`;
}

function settle(file, output) {
  if (!check) {
    writeFileSync(file, output);
    return;
  }
  const existing = existsSync(file) ? readFileSync(file, "utf8") : "";
  if (existing !== output) {
    console.error(`${path.relative(workspaceRoot, file)} is stale; run pnpm runx-maintained-connectors:generate`);
    process.exit(1);
  }
}
// The contract is read from the source tree, never from the embedded table, so
// the runtime that prints it may be built before the table is rewritten.
const contract = runxMaintainedConnectors();
settle(outputPath, render(contract));
settle(contractsPath, renderContracts(contract));
settle(lockPath, renderLock());
