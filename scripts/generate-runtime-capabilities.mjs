#!/usr/bin/env node
// Embed the runtime capability connectors (a manifest declaring
// `runtime_capability: true`) in the runtime: they are part of runx, implemented
// by the runtime and shipping no tool package, so an installed runx resolves
// them without the source tree or a registry. Every other connector here is
// published like any publisher's, with `runx registry publish`. Each connector
// is read as `runx registry package` reads it, so a manifest or tool the
// runtime would refuse fails the generation.
import { spawnSync } from "node:child_process";
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { resolveNativeRunxBinary } from "./lib/native-parser.mjs";

const workspaceRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const connectorsRoot = path.join(workspaceRoot, "connectors");
const outputPath = path.join(
  workspaceRoot,
  "crates",
  "runx-runtime",
  "src",
  "kernel",
  "connectors",
  "runtime_capabilities.rs",
);
const check = process.argv.includes("--check");
const delimiter = "###";

// Every connector by name: a leaf at connectors/<name>/, a surface at
// connectors/<namespace>/<surface>/, as the runtime reads a plugin.
function connectorIds() {
  const directories = (dir) => readdirSync(dir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && !entry.name.startsWith("."))
    .map((entry) => entry.name)
    .sort();
  return directories(connectorsRoot).flatMap((namespace) => {
    if (existsSync(path.join(connectorsRoot, namespace, "connector.yaml"))) return [namespace];
    const surfaces = directories(path.join(connectorsRoot, namespace))
      .filter((surface) => existsSync(path.join(connectorsRoot, namespace, surface, "connector.yaml")))
      .map((surface) => `${namespace}/${surface}`);
    if (surfaces.length === 0) throw new Error(`connectors/${namespace} holds no connector.yaml`);
    return surfaces;
  });
}

// Whether the runtime reads the connector at `id` as a runtime capability.
function isRuntimeCapability(binary, id) {
  const result = spawnSync(binary, ["registry", "package", path.join("connectors", id), "--json"], {
    cwd: workspaceRoot,
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
  });
  if (result.error) throw result.error;
  if (result.status !== 0) throw new Error(`connectors/${id}: ${result.stderr || result.stdout}`);
  const connector = JSON.parse(result.stdout).registry?.connector;
  if (connector?.ref !== id) throw new Error(`connectors/${id} packaged as ${connector?.ref}`);
  return connector.manifest.runtime_capability === true;
}

function literal(fields) {
  const source = fields.at(-1);
  if (source.includes(`"${delimiter}`)) {
    throw new Error(`${fields.slice(0, -1).join("/")} contains the raw string delimiter`);
  }
  const names = fields.slice(0, -1).map((field) => `        "${field}",\n`).join("");
  return `    (\n${names}        r${delimiter}"${source}"${delimiter},\n    ),`;
}

function render(embedded) {
  const read = (...parts) => readFileSync(path.join(connectorsRoot, ...parts), "utf8");
  const assets = embedded.flatMap((id) => ["README.md", "mark.svg"]
    .filter((file) => existsSync(path.join(connectorsRoot, id, file)))
    .map((file) => [id, file, read(id, file)]));
  return [
    "// Generated by scripts/generate-runtime-capabilities.mjs; do not edit.",
    "// Module rationale: the embedded runtime capability manifests are one generated",
    "// table so a change is a single mechanical, reviewable diff.",
    "",
    "/// Runtime capability connector manifests, by id.",
    "pub(super) const CONNECTORS: &[(&str, &str)] = &[",
    ...embedded.map((id) => literal([id, read(id, "connector.yaml")])),
    "];",
    "",
    "/// Public package assets, retained so offline snapshots preserve published bytes.",
    "pub(super) const ASSETS: &[(&str, &str, &str)] = &[",
    ...assets.map(literal),
    "];",
    "",
  ].join("\n");
}

const binary = resolveNativeRunxBinary();
const embedded = connectorIds().filter((id) => isRuntimeCapability(binary, id));
for (const id of embedded) {
  if (existsSync(path.join(connectorsRoot, id, "tools"))) {
    throw new Error(`connectors/${id} is a runtime capability, implemented by the runtime; it ships no tools/`);
  }
}
const output = render(embedded);
if (check) {
  if ((existsSync(outputPath) ? readFileSync(outputPath, "utf8") : "") !== output) {
    console.error(`${path.relative(workspaceRoot, outputPath)} is stale; run pnpm runtime-capabilities:generate`);
    process.exit(1);
  }
} else {
  writeFileSync(outputPath, output);
}
console.log(`${check ? "checked" : "generated"} ${embedded.length} runtime capabilities`);
